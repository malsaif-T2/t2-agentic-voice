// `text` with each "{key}" replaced by `values[key]`, as text.
export function fill(text, values) {
  return String(text).replace(/\{(\w+)\}/g, (whole, key) => (key in values ? String(values[key]) : whole));
}

// The texts of a page language ("ar-SA" or "en").
export function wordsOf(language) {
  return TEXT[language === "en" ? "en" : "ar"];
}
