"""The run history: `apps/ole5-voice-agent/evals/history.jsonl`, one `HistoryLine` per `poe eval`
run that called a provider, kept or not (evaluation.md, "Run history"), one `EotLine` per
`poe eot` run of the pipeline, one `TimingLine` per `poe eval-timing` run and one `OverlapLine`
per `poe overlap` run of the replay (run_lines.py); for plan 006's runs, a `TalkerLine` per
session of `poe eval-talker`, a `ScenarioLine` per session of `poe eval-scenarios`
(talker_lines.py), an `UncertainLine` per `poe uncertain` run and a `FirstAudioLine` per
`poe first-audio` run (measure_lines.py); and `poe eval-history`, which renders it into
`docs/generated/eval-history.md` (GP-11), each kind's table but `poe eval`'s written by
history_tables.py, and plan 006's kinds' by history_measures.py.

The file is read strictly: every line a valid history line with an LF ending, so a line is only
ever appended to a well-formed history, and a line made with `model_copy` (a secret setting's
value, say) is checked again before it is written, serialized with pydantic's warnings off, whose
text would quote the value it refuses. `line_of` is the one definition of a run's line;
`render_history` is the pure renderer the command and the freshness test both call.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Final

from pydantic import TypeAdapter
from t2_agentic_voice import configure_logging, get_logger

from ole5_voice import LOGGERS
from ole5_voice.evals.files import parse_json, read_text
from ole5_voice.evals.history_measures import (
    first_audio_rows,
    measure_prices,
    measure_strata,
    scenario_rows,
    talker_rows,
    uncertain_rows,
)
from ole5_voice.evals.history_tables import (
    cell,
    eot_rows,
    overlap_rows,
    percent,
    row,
    strata,
    timing_rows,
)
from ole5_voice.evals.items import EVALS, HISTORY_FILE
from ole5_voice.evals.measure_lines import FirstAudioLine, UncertainLine
from ole5_voice.evals.run_lines import AnyLine, EotLine, OverlapLine, TimingLine
from ole5_voice.evals.runs import SCORECARD_FILE, HistoryLine, Scorecard, StratumValue
from ole5_voice.evals.scorecard import EvalDataError
from ole5_voice.evals.talker_lines import ScenarioLine, TalkerLine

HISTORY: Final = EVALS / HISTORY_FILE
DOC: Final = EVALS.parents[2] / "docs" / "generated" / "eval-history.md"  # the repository's
_DESCRIPTION = "Render the golden set's run history into docs/generated/eval-history.md."
log = get_logger(__name__)
_LINE: Final[TypeAdapter[AnyLine]] = TypeAdapter(AnyLine)
# The kinds whose lines bill audio, and plan 006's kinds (history_measures.py).
_BILLED: Final = (HistoryLine, TimingLine, OverlapLine, FirstAudioLine)
_MEASURES: Final = (TalkerLine, ScenarioLine, UncertainLine, FirstAudioLine)
_HEADER = """# Run history

Generated by `uv run poe eval-history` from `apps/ole5-voice-agent/evals/history.jsonl`, one line
per `poe eval` run that called a provider, kept or not; never edited by hand
([generated docs](README.md), GP-11). Every number describes one speaker, the owner (D-006).
Full scorecards stay out of git, in each run's `--out` folder.
"""


def read_history(path: Path) -> tuple[AnyLine, ...]:
    """Every line of the history at `path`, in order; `EvalDataError` naming the first line that
    is not a valid history line with an LF ending."""
    text = read_text(path)
    if text is None:
        raise EvalDataError(f"{path} is not a readable UTF-8 file")
    if text and not text.endswith("\n"):
        raise EvalDataError(f"{path}: its last line has no LF ending")
    lines: list[AnyLine] = []
    for number, raw in enumerate(text.split("\n")[:-1], start=1):
        if "\r" in raw:
            raise EvalDataError(f"{path}, line {number}: a CR; the history has LF endings")
        lines.append(_history_line(raw, f"{path}, line {number}: "))
    return tuple(lines)


def _history_line(text: str, where: str = "") -> AnyLine:
    """`text` as a history line; `EvalDataError` naming the fields only (`files.parse_json`)."""
    return parse_json(
        _LINE, text, lambda problem: EvalDataError(f"{where}not a history line ({problem})")
    )


def append_line(line: AnyLine, history: Path) -> None:
    """Add `line` to the end of `history` (created if missing), as one line of JSON with an LF
    ending, once the line and every line already there pass their checks."""
    checked = _history_line(line.model_dump_json(warnings=False))
    if history.exists():
        read_history(history)
    with history.open("ab") as file:
        file.write(checked.model_dump_json().encode("utf-8") + b"\n")


def line_of(
    scorecard: Scorecard, *, items: int, billed_seconds: float, cost_usd: float
) -> HistoryLine:
    """The history line of a run's scorecard: its totals, each stratum value's accuracy and
    items (a held-out run's pooled as its scorecard's are), the run's price and the scorecard's
    file name; `items` is the run's item count, which a held-out scorecard, holding no variant,
    cannot give. `billed_seconds` and `cost_usd` are the run's spend, every request it sent (its
    budget's): the scorecard's own cover only the variants it scores, without the smoke test's
    request, a variant cut off at the cap, or an unfinished held-out run's results."""
    run, totals = scorecard.run, scorecard.totals
    return HistoryLine(
        time=run.started_at,
        commit=run.commit,
        run=run.name,
        answerer=run.answerer,
        model=run.model,
        settings=run.settings,
        split=run.split,
        items=items,
        variants=totals.variants,
        accuracy=totals.accuracy,
        violations=scorecard.violations,
        billed_seconds=billed_seconds,
        price_per_hour_usd=run.price_per_hour_usd,
        cost_usd=cost_usd,
        latency_median_ms=totals.latency_median_ms,
        breakdowns={
            stratum: {
                value: StratumValue(items=metrics.items, accuracy=metrics.accuracy)
                for value, metrics in values.items()
            }
            for stratum, values in scorecard.breakdowns.items()
        },
        scorecard=SCORECARD_FILE,
        data_digest=run.data_digest,
        note=run.note,
        complete=scorecard.complete,
    )


def render_history(lines: Sequence[AnyLine]) -> str:
    """`docs/generated/eval-history.md` for `lines`: the spend so far, a row per run in its
    kind's table (`poe eval`'s, then the end-of-turn, timing and overlap runs', then plan 006's
    talker, scenario, uncertain-middle and first-audio runs', each shown only when it has a
    run), and each run's reason, data, prices, settings and numbers by stratum value."""
    if not lines:
        return f"{_HEADER}\nNo runs yet.\n"
    billed = sum(line.billed_seconds for line in lines if isinstance(line, _BILLED))
    cost = sum(line.cost_usd for line in lines if not isinstance(line, EotLine))
    numbered = list(enumerate(lines, start=1))
    parts = [
        _HEADER,
        f"Spend so far: {len(lines)} run(s), {billed:.1f} billed seconds, ${cost:.4f}.\n",
        "## Runs\n",
        "| # | Time | Run | Commit | Answerer | Model | Split | Items | Variants | Accuracy "
        "| Violations | Billed seconds | Cost | Median latency (ms) | Complete |\n"
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- "
        "| --- |",
    ]
    parts += [
        row(
            str(number),
            line.time.isoformat(timespec="seconds"),
            line.run,
            line.commit,
            line.answerer,
            cell(line.model) if line.model else "—",
            line.split,
            str(line.items),
            str(line.variants),
            percent(line.accuracy),
            str(line.violations),
            f"{line.billed_seconds:.1f}",
            f"${line.cost_usd:.4f}",
            "—" if line.latency_median_ms is None else f"{line.latency_median_ms:.0f}",
            "yes" if line.complete else "no",
        )
        for number, line in numbered
        if isinstance(line, HistoryLine)
    ]
    parts += eot_rows([(n, line) for n, line in numbered if isinstance(line, EotLine)])
    parts += timing_rows([(n, line) for n, line in numbered if isinstance(line, TimingLine)])
    parts += overlap_rows([(n, line) for n, line in numbered if isinstance(line, OverlapLine)])
    parts += talker_rows([(n, line) for n, line in numbered if isinstance(line, TalkerLine)])
    parts += scenario_rows([(n, line) for n, line in numbered if isinstance(line, ScenarioLine)])
    parts += uncertain_rows([(n, line) for n, line in numbered if isinstance(line, UncertainLine)])
    parts += first_audio_rows([(n, ln) for n, ln in numbered if isinstance(ln, FirstAudioLine)])
    parts.append("\n## Each run")
    for number, line in numbered:
        parts += [f"\n### {number} · {line.run}\n", "| Field | Value |\n| --- | --- |"]
        parts.append(row("Why", cell(line.note)))
        parts.append(row("Data digest", f"`{line.data_digest}`"))
        parts.append(row("Scorecard", cell(line.scorecard)))
        if isinstance(line, _MEASURES):
            parts += measure_prices(line)
        elif not isinstance(line, EotLine):
            parts.append(row("Price per hour of audio", f"${line.price_per_hour_usd:g}"))
        if isinstance(line, TimingLine):
            parts += [
                row(f"Price per million characters, {cell(model)}", f"${price:g}")
                for model, price in sorted(line.tts_price_per_million_usd.items())
            ]
        parts += [
            row(f"Setting {cell(name)}", cell(value))
            for name, value in sorted(line.settings.items())
        ]
        parts += measure_strata(line) if isinstance(line, _MEASURES) else strata(line)
    return "\n".join(parts) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    """`uv run poe eval-history`: render the run history into docs/generated/eval-history.md."""
    parser = argparse.ArgumentParser(prog="poe eval-history", description=_DESCRIPTION)
    parser.add_argument(
        "--history", type=Path, default=HISTORY, help="the history to read (default: %(default)s)"
    )
    parser.add_argument(
        "--out", type=Path, default=DOC, help="the page to write (default: %(default)s)"
    )
    args = parser.parse_args(argv)
    configure_logging(loggers=LOGGERS)
    try:
        lines = read_history(args.history)
    except EvalDataError as error:
        log.error("history_not_rendered", code=error.code, message=error.message)
        return 1
    args.out.write_bytes(render_history(lines).encode("utf-8"))
    log.info("history_rendered", out=str(args.out), runs=len(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
